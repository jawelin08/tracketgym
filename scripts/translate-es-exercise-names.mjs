#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = join(root, 'scripts', 'exercise-name-sources', 'es.json')
const outputPath = join(root, 'frontend', 'src', 'exercise-names', 'es.js')
const exercisesPath = join(root, 'frontend', 'src', 'lib', 'exercises-data.js')
const option = name => process.argv.find(arg => arg.startsWith(`--${name}=`))?.split('=').slice(1).join('=')
const limit = Number(option('limit') || Number.MAX_SAFE_INTEGER)
const batchSize = Number(option('batch-size') || 30)
const delayMs = Number(option('delay-ms') || 350)
const apply = process.argv.includes('--apply')

if (!Number.isInteger(limit) || limit < 1 || !Number.isInteger(batchSize) || batchSize < 1 || !Number.isInteger(delayMs) || delayMs < 0) {
  throw new Error('limit and batch-size must be positive integers; delay-ms must be a non-negative integer')
}

const { EXDB } = await import(pathToFileURL(exercisesPath))
const known = new Set(EXDB.map(exercise => exercise.id))
const translations = existsSync(sourcePath) ? JSON.parse(readFileSync(sourcePath, 'utf8')) : {}
for (const [id, name] of Object.entries(translations)) {
  if (!known.has(id)) throw new Error(`Unknown exercise ID in Spanish source: ${id}`)
  if (typeof name !== 'string' || !name.trim()) throw new Error(`${id}: translation must be a non-empty string`)
}

const pending = EXDB.filter(exercise => !translations[exercise.id]).slice(0, limit)
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))

async function translateBatch(batch) {
  const input = batch.map(exercise => exercise.n).join('\n')
  const params = new URLSearchParams({ client: 'gtx', sl: 'en', tl: 'es', dt: 't', q: input })
  let lastError
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const response = await fetch(`https://translate.googleapis.com/translate_a/single?${params}`, {
        signal: AbortSignal.timeout(20000)
      })
      if (!response.ok) throw new Error(`Translator returned HTTP ${response.status}`)
      const payload = await response.json()
      const translatedText = payload?.[0]?.map(part => part?.[0] || '').join('')
      if (typeof translatedText !== 'string') throw new Error('Translator returned an invalid response')
      const rows = translatedText.split('\n').map(name => name.trim())
      if (rows.length !== batch.length || rows.some(name => !name)) {
        throw new Error(`Expected ${batch.length} translated lines, received ${rows.length}`)
      }
      return rows
    } catch (error) {
      lastError = error
      if (attempt < 3) await pause(1000 * (attempt + 1))
    }
  }
  throw lastError
}

for (let start = 0; start < pending.length; start += batchSize) {
  const batch = pending.slice(start, start + batchSize)
  const names = await translateBatch(batch)
  for (let index = 0; index < batch.length; index++) translations[batch[index].id] = names[index]
  console.log(`Translated ${Math.min(start + batch.length, pending.length)}/${pending.length} pending names`)
  if (apply) writeFileSync(sourcePath, JSON.stringify(translations, null, 2) + '\n')
  if (start + batch.length < pending.length) await pause(delayMs)
}

if (!apply) {
  console.log(`Validated ${pending.length} names without writing. Re-run with --apply to save them.`)
} else {
  const ordered = {}
  for (const exercise of EXDB) {
    if (!translations[exercise.id]) throw new Error(`Missing Spanish name: ${exercise.id}`)
    ordered[exercise.id] = translations[exercise.id].trim()
  }
  writeFileSync(sourcePath, JSON.stringify(ordered, null, 2) + '\n')
  writeFileSync(outputPath, '// generated by scripts/translate-es-exercise-names.mjs\nexport default ' + JSON.stringify(ordered) + '\n')
  console.log(`Generated Spanish names for all ${EXDB.length} exercises.`)
}
